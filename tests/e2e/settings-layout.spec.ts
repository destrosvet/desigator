import { expect, test } from "@playwright/test";
import { teacherStatePath } from "./auth-setup";
test.skip(process.env.E2E_WORKFLOW !== "true", "Requires isolated seeded database");
test("administrator settings separate organizations, school management and personal preferences", async ({ browser, baseURL }, testInfo) => {
  const context = await browser.newContext({ baseURL }); const teacherContext = await browser.newContext({ baseURL, storageState: teacherStatePath });
  try {
    const page = await context.newPage();
    await page.goto("/cs/auth/login"); await page.getByLabel(/e-mail/i).fill("admin@desigator.cz"); await page.getByLabel(/heslo/i).fill("admin123"); await page.getByRole("button", { name: /přihlásit/i }).click(); await expect(page).toHaveURL(/dashboard/);
    await page.goto("/cs/settings");
    await expect(page.getByRole("tab", { name: "Organizace", exact: true })).toHaveAttribute("data-state", "active");
    await expect(page.getByRole("table")).toBeVisible();
    await expect(page.getByRole("button", { name: "Nová šablona", exact: true })).toHaveCount(0);
    await expect(page.getByRole("textbox", { name: "E-mail pozvaného", exact: true })).toHaveCount(0);
    await page.screenshot({ path: testInfo.outputPath("admin-settings-organizations.png"), fullPage: true });
    const teacher = await teacherContext.newPage();
    expect((await teacher.request.get("/api/admin/organizations")).status()).toBe(403);
    expect((await teacher.request.patch("/api/admin/organizations", { data: { id: "legacy", name: "Forbidden" } })).status()).toBe(403);
    const list = (await (await page.request.get("/api/admin/organizations")).json()).organizations;
    expect(list.length).toBeGreaterThan(0);
    expect((await (await page.request.get("/api/organization")).json()).organization).toBeNull();
    await expect(page.getByRole("tab", { name: "Moje škola a členové", exact: true })).toHaveCount(0);
    await expect(page.getByRole("tab", { name: "Působení ve škole", exact: true })).toHaveCount(0);
    await expect(page.getByRole("tab", { name: "Moje šablony", exact: true })).toHaveCount(0);
    const own = list.find((item: { id: string }) => item.id === "legacy") || list[0];
    const row = page.getByRole("row", { name: "Otevřít: " + own.name, exact: true }); await row.click();
    const changed = own.name + " – test";
    await page.getByLabel("Název organizace", { exact: true }).fill(changed);
    await page.getByRole("button", { name: "Uložit organizaci", exact: true }).click();
    await expect(page.getByRole("dialog")).toBeHidden();
    expect((await (await page.request.get("/api/admin/organizations")).json()).organizations.find((item: { id: string }) => item.id === own.id).name).toBe(changed);
    expect((await page.request.patch("/api/admin/organizations", { data: { id: own.id, name: own.name } })).status()).toBe(200);
    await page.getByRole("row", { name: "Otevřít: " + changed, exact: true }).click();
    await page.getByRole("button", { name: "Spravovat členy", exact: true }).click();
    await expect(page.getByText("Správa organizace jako správce platformy", { exact: true })).toBeVisible();
    await expect(page.getByRole("textbox", { name: "Vyhledat člena školy…", exact: true })).toBeVisible();
    await page.getByRole("button", { name: "Pozvat člena", exact: true }).click();
    await expect(page.getByRole("dialog").getByLabel("E-mail pozvaného", { exact: true })).toBeVisible();
    await page.keyboard.press("Escape");
    await page.getByRole("row", { name: "Otevřít: Pan Učitel", exact: true }).click();
    await expect(page.getByRole("dialog", { name: "Oprávnění člena školy", exact: true })).toBeVisible(); await page.keyboard.press("Escape");
    await page.getByRole("tab", { name: "Můj profil", exact: true }).click();
    await expect(page.getByRole("table")).toHaveCount(0);
    await expect(page.getByRole("definition").filter({ hasText: "admin@desigator.cz" })).toBeVisible();
    await page.reload(); await expect(page.getByRole("tab", { name: "Můj profil", exact: true })).toHaveAttribute("data-state", "active");
    await page.getByRole("tab", { name: "Vzhled", exact: true }).click(); await expect(page.getByRole("button", { name: "Tmavý", exact: true })).toBeVisible();
    await page.setViewportSize({ width: 390, height: 844 }); await page.getByRole("tab", { name: "Organizace", exact: true }).click();
    await expect(page.getByRole("table")).toBeVisible(); await page.screenshot({ path: testInfo.outputPath("admin-settings-mobile.png"), fullPage: true });
    await teacher.goto("/cs/settings?section=organizations");
    await expect(teacher.getByRole("tab", { name: "Organizace", exact: true })).toHaveCount(0);
    await expect(teacher.getByRole("tab", { name: "Můj profil", exact: true })).toHaveAttribute("data-state", "active");
  } finally { await context.close(); await teacherContext.close(); }
});
